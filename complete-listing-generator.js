async function generateListing() {

    const product = document.getElementById("product").value.trim();
    const brand = document.getElementById("brand").value.trim();
    const category = document.getElementById("category").value.trim();
    const material = document.getElementById("material").value.trim();
    const color = document.getElementById("color").value.trim();
    const audience = document.getElementById("audience").value;
    const extra = document.getElementById("extra").value.trim();

    if (product === "" || category === "") {
        alert("कृपया Product Name और Category भरें।");
        return;
    }

    const titleResult = document.getElementById("titleResult");
    const descriptionResult = document.getElementById("descriptionResult");
    const bulletResult = document.getElementById("bulletResult");
    const featureResult = document.getElementById("featureResult");
    const keywordResult = document.getElementById("keywordResult");
    const hashtagResult = document.getElementById("hashtagResult");
    const tagResult = document.getElementById("tagResult");

    titleResult.value = "⏳ Generating...";
    descriptionResult.value = "⏳ Generating...";
    bulletResult.value = "⏳ Generating...";
    featureResult.value = "⏳ Generating...";
    keywordResult.value = "⏳ Generating...";
    hashtagResult.value = "⏳ Generating...";
    tagResult.value = "⏳ Generating...";

    const prompt = `
You are a professional eCommerce product listing specialist.

Create a complete product listing using ONLY the information provided below.

Product Name: ${product}
Brand: ${brand || "Not specified"}
Category: ${category}
Material: ${material || "Not specified"}
Color: ${color || "Not specified"}
Target Audience: ${audience}
Extra Information: ${extra || "Not specified"}

Create all of the following:

1. SEO PRODUCT TITLE
Create 3 professional SEO-friendly product titles.

2. PRODUCT DESCRIPTION
Write one professional product description of about 120-180 words.

3. BULLET POINTS
Create 5 concise customer-friendly bullet points.

4. PRODUCT FEATURES
Create 10 useful product features.

5. SEO KEYWORDS
Create 20 relevant SEO keywords.

6. HASHTAGS
Create 10 relevant hashtags.

7. PRODUCT TAGS
Create 15 relevant product tags.

Important rules:
- Suitable for Amazon, Flipkart, Meesho and Shopify.
- Use only the information provided.
- Do not invent specifications.
- Do not make medical, guaranteed or misleading claims.
- Keep the content professional and easy to read.
- Avoid keyword stuffing.
- Do not mention that the content was generated by AI.

Return the result using exactly these section headings:

SEO PRODUCT TITLE:
[3 titles]

PRODUCT DESCRIPTION:
[description]

BULLET POINTS:
[5 bullet points]

PRODUCT FEATURES:
[10 features]

SEO KEYWORDS:
[20 keywords]

HASHTAGS:
[10 hashtags]

PRODUCT TAGS:
[15 tags]
`;

    try {

        const response = await fetch(
            "https://ai-seller-toolkit-backend-1.onrender.com/generate",
            {
                method: "POST",

                headers: {
                    "Content-Type": "application/json"
                },

                body: JSON.stringify({
                    prompt: prompt
                })
            }
        );

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.error || "Server error");
        }

        const text = data.result || "";

        titleResult.value = extractSection(
            text,
            "SEO PRODUCT TITLE:",
            "PRODUCT DESCRIPTION:"
        );

        descriptionResult.value = extractSection(
            text,
            "PRODUCT DESCRIPTION:",
            "BULLET POINTS:"
        );

        bulletResult.value = extractSection(
            text,
            "BULLET POINTS:",
            "PRODUCT FEATURES:"
        );

        featureResult.value = extractSection(
            text,
            "PRODUCT FEATURES:",
            "SEO KEYWORDS:"
        );

        keywordResult.value = extractSection(
            text,
            "SEO KEYWORDS:",
            "HASHTAGS:"
        );

        hashtagResult.value = extractSection(
            text,
            "HASHTAGS:",
            "PRODUCT TAGS:"
        );

        tagResult.value = extractSection(
            text,
            "PRODUCT TAGS:",
            null
        );

    } catch (error) {

        console.error("Listing AI Error:", error);

        const message =
            "❌ AI listing नहीं बन सकी.\n\n" +
            "Error: " + error.message;

        titleResult.value = message;
        descriptionResult.value = message;
        bulletResult.value = message;
        featureResult.value = message;
        keywordResult.value = message;
        hashtagResult.value = message;
        tagResult.value = message;
    }
}


function extractSection(text, startHeading, endHeading) {

    const start = text.indexOf(startHeading);

    if (start === -1) {
        return "";
    }

    const contentStart = start + startHeading.length;

    let end;

    if (endHeading) {
        end = text.indexOf(endHeading, contentStart);
    } else {
        end = text.length;
    }

    if (end === -1) {
        end = text.length;
    }

    return text
        .substring(contentStart, end)
        .trim();
}


function copyAll() {

    const title = document.getElementById("titleResult").value;
    const description = document.getElementById("descriptionResult").value;
    const bullets = document.getElementById("bulletResult").value;
    const features = document.getElementById("featureResult").value;
    const keywords = document.getElementById("keywordResult").value;
    const hashtags = document.getElementById("hashtagResult").value;
    const tags = document.getElementById("tagResult").value;

    const completeListing =
`SEO PRODUCT TITLE:
${title}

PRODUCT DESCRIPTION:
${description}

BULLET POINTS:
${bullets}

PRODUCT FEATURES:
${features}

SEO KEYWORDS:
${keywords}

HASHTAGS:
${hashtags}

PRODUCT TAGS:
${tags}`;

    if (title.trim() === "") {
        alert("पहले Complete Listing generate करें।");
        return;
    }

    navigator.clipboard.writeText(completeListing)
        .then(function () {
            alert("✅ Complete Listing copied successfully!");
        })
        .catch(function () {
            alert("❌ Copy नहीं हो सका।");
        });
}


