async function generateListing() {

    const product = document.getElementById("product").value.trim();
    const brand = document.getElementById("brand").value.trim();
    const category = document.getElementById("category").value.trim();
    const material = document.getElementById("material").value.trim();
    const color = document.getElementById("color").value.trim();
    const audience = document.getElementById("audience").value;
    const extra = document.getElementById("extra").value.trim();

    if (product === "" || category === "") {
        alert("कृपया Product Name और Category भरें।");
        return;
    }

    const titleResult = document.getElementById("titleResult");
    const descriptionResult = document.getElementById("descriptionResult");
    const bulletResult = document.getElementById("bulletResult");
    const featureResult = document.getElementById("featureResult");
    const keywordResult = document.getElementById("keywordResult");
    const hashtagResult = document.getElementById("hashtagResult");
    const tagResult = document.getElementById("tagResult");

    titleResult.value = "⏳ Generating...";
    descriptionResult.value = "⏳ Generating...";
    bulletResult.value = "⏳ Generating...";
    featureResult.value = "⏳ Generating...";
    keywordResult.value = "⏳ Generating...";
    hashtagResult.value = "⏳ Generating...";
    tagResult.value = "⏳ Generating...";

    const prompt = `
You are a STRICT eCommerce product listing generator.

Your most important rule is:

USE ONLY FACTS PROVIDED BY THE USER.

Do NOT invent, assume, exaggerate, or infer any product specification, benefit, quality, performance, comfort, durability, certification, feature, size, fit, use case, or material property.

USER PROVIDED INFORMATION:

Product Name: ${product}
Brand: ${brand || "Not specified"}
Category: ${category}
Material: ${material || "Not specified"}
Color: ${color || "Not specified"}
Target Audience: ${audience}
Extra Information: ${extra || "Not specified"}

STRICT CONTENT RULES:

1. Never add information that is not explicitly provided.
2. Never use words such as:
   premium, superior, best, excellent, high quality, luxury,
   durable, long-lasting, comfortable, soft, breathable,
   lightweight, waterproof, guaranteed, authentic,
   unless that exact information was provided by the user.
3. Do not assume that a material has a specific property.
4. Do not assume the product is suitable for a particular activity.
5. Do not claim that the product is suitable for daily use unless the user says so.
6. Do not claim a product is durable unless the user says it is durable.
7. Do not claim comfort unless the user provides comfort information.
8. Do not create technical specifications.
9. Do not create measurements, sizes, weight, warranty, certifications, or performance claims.
10. Brand name may be used exactly as provided.
11. Product name, category, material, color and audience may be repeated naturally.
12. SEO keywords must remain directly relevant to the supplied information.
13. Do not use misleading marketing claims.
14. Do not use fake customer benefits.
15. Do not mention that this content was generated by AI.

IMPORTANT:
If information is missing, simply do not mention that information.
Do not replace missing information with assumptions.

CREATE:

1. SEO PRODUCT TITLE
Create 3 titles.
Use only supplied facts.

2. PRODUCT DESCRIPTION
Write approximately 100-150 words.
Use only supplied facts.
Do not add unsupported benefits.

3. BULLET POINTS
Create 5 bullet points.
Every bullet must be based directly on supplied information.

4. PRODUCT FEATURES
Create 10 features.
If there are not enough real features provided, use factual attributes such as product name, category, brand, material, color and target audience instead of inventing features.

5. SEO KEYWORDS
Create 20 relevant keywords.
Do not create keywords based on unsupported claims.

6. HASHTAGS
Create 10 relevant hashtags.
Use only supplied product information.

7. PRODUCT TAGS
Create 15 relevant tags.
Use only supplied product information.

The listing should be suitable for Amazon, Flipkart, Meesho and Shopify.

Return ONLY these exact section headings:

SEO PRODUCT TITLE:

PRODUCT DESCRIPTION:

BULLET POINTS:

PRODUCT FEATURES:

SEO KEYWORDS:

HASHTAGS:

PRODUCT TAGS:
`;

    try {

        const response = await fetch(
            "https://ai-seller-toolkit-backend-1.onrender.com/generate",
            {
                method: "POST",

                headers: {
                    "Content-Type": "application/json"
                },

                body: JSON.stringify({
                    prompt: prompt
                })
            }
        );

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.error || "Server error");
        }

        const text = data.result || "";

        titleResult.value = extractSection(
            text,
            "SEO PRODUCT TITLE:",
            "PRODUCT DESCRIPTION:"
        );

        descriptionResult.value = extractSection(
            text,
            "PRODUCT DESCRIPTION:",
            "BULLET POINTS:"
        );

        bulletResult.value = extractSection(
            text,
            "BULLET POINTS:",
            "PRODUCT FEATURES:"
        );

        featureResult.value = extractSection(
            text,
            "PRODUCT FEATURES:",
            "SEO KEYWORDS:"
        );

        keywordResult.value = extractSection(
            text,
            "SEO KEYWORDS:",
            "HASHTAGS:"
        );

        hashtagResult.value = extractSection(
            text,
            "HASHTAGS:",
            "PRODUCT TAGS:"
        );

        tagResult.value = extractSection(
            text,
            "PRODUCT TAGS:",
            null
        );

    } catch (error) {

        console.error("Listing AI Error:", error);

        const message =
            "❌ AI listing नहीं बन सकी.\n\n" +
            "Error: " + error.message;

        titleResult.value = message;
        descriptionResult.value = message;
        bulletResult.value = message;
        featureResult.value = message;
        keywordResult.value = message;
        hashtagResult.value = message;
        tagResult.value = message;
    }
}


function extractSection(text, startHeading, endHeading) {

    const start = text.indexOf(startHeading);

    if (start === -1) {
        return "";
    }

    const contentStart = start + startHeading.length;

    let end;

    if (endHeading) {
        end = text.indexOf(endHeading, contentStart);
    } else {
        end = text.length;
    }

    if (end === -1) {
        end = text.length;
    }

    return text
        .substring(contentStart, end)
        .trim();
}


function copyAll() {

    const title = document.getElementById("titleResult").value;
    const description = document.getElementById("descriptionResult").value;
    const bullets = document.getElementById("bulletResult").value;
    const features = document.getElementById("featureResult").value;
    const keywords = document.getElementById("keywordResult").value;
    const hashtags = document.getElementById("hashtagResult").value;
    const tags = document.getElementById("tagResult").value;

    const completeListing =
`SEO PRODUCT TITLE:
${title}

PRODUCT DESCRIPTION:
${description}

BULLET POINTS:
${bullets}

PRODUCT FEATURES:
${features}

SEO KEYWORDS:
${keywords}

HASHTAGS:
${hashtags}

PRODUCT TAGS:
${tags}`;

    if (title.trim() === "") {
        alert("पहले Complete Listing generate करें।");
        return;
    }

    navigator.clipboard.writeText(completeListing)
        .then(function () {
            alert("✅ Complete Listing copied successfully!");
        })
        .catch(function () {
            alert("❌ Copy नहीं हो सका।");
        });
}


