/* =====================================================
   CLEAN AI OUTPUT
===================================================== */

function cleanTermsOutput(text) {

    let cleaned =
        text.trim();


    // Remove Markdown code fences

    cleaned =
        cleaned.replace(
            /^```(?:text|markdown)?\s*/i,
            ""
        );


    cleaned =
        cleaned.replace(
            /\s*```$/i,
            ""
        );


    // Remove accidental leading/trailing spaces

    cleaned =
        cleaned.trim();


    return cleaned;

}


